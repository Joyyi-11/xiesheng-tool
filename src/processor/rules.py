# 二、结构化产物口径（STRUCT_*）
# 供 session_edit「输出结构」与 prompt.STRUCT_SYSTEM_PROMPT 共同引用。
# 描述最终产物的「形态 + 内容要求」，与流程/渲染细节解耦。
