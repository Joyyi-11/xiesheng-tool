    "**观点句必须是完整陈述句、以句号结尾，句号后直接接展开句，"
    "严禁用冒号把展开句挂在主题句后面**"
    "（反例「**AI 产品的第三个时代：常驻同事**：Tara 把演进划为三段」应写成"
