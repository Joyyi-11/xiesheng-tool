"""编辑口径单一权威源（session 链路与 api 链路共用）。

历史教训：session 链路的 ``SESSION_RULES``（session_edit.py）与 api 链路的
``CLEAN/STRUCT_SYSTEM_PROMPT``（prompt.py）曾是两份人工同步的独立文本，
没有任何机制保证一致——v17 冒号事故即实证（api 链路每期必带框架冒号、
session 链路本就正确，两路漂移）。

连漪（2026-09-07）拍板：两条链路本质都是调用大模型，只是调用方式不同，
**编辑口径必须完全一致**（规则层单一权威源；流程层可不同——session 一次
成型 vs api 分块校订/JSON 结构化）。

本模块即规则层的唯一来源：

* ``RULES_SPEC_VERSION`` —— 共享口径版本。任何条款变更时递增，三条链路
  （session 提示词 / api CLEAN / api STRUCT）的版本号同步引用它，
  保证「改口径必三处同版本」。
* ``EDIT_*`` —— 校订口径条款（错字/断句/标点/填充词/说话人合并等）。
  供 session 的「校订规则」与 api 的 CLEAN 提示词共同引用。
* ``STRUCT_*`` —— 结构化产物口径条款（摘要/核心观点/问题/术语表/人物简介/
  说话人映射/回标锚点）。供 session 的「输出结构」与 api 的 STRUCT 提示词
  共同引用。

组装规则时请逐条引用本模块常量，不要在本模块之外改写条款文字。
"""

